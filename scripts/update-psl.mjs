#!/usr/bin/env node
// Regenerate the offline PSL module from the checked-in canonical source; no network.
// To update, download https://publicsuffix.org/list/public_suffix_list.dat into
// browser/vendor/public_suffix_list.dat, review the diff, then run this script.
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {domainToASCII} from 'node:url';
const sourceUrl = new URL('../browser/vendor/public_suffix_list.dat', import.meta.url);
const raw = readFileSync(sourceUrl, 'utf8');
if (!raw.includes('// ===END PRIVATE DOMAINS===')) throw new Error('Incomplete PSL source');
const rules = raw.split(/\r?\n/).map(x => x.trim()).filter(x => x && !x.startsWith('//')).map(x => {
  const prefix = x.startsWith('!') ? '!' : x.startsWith('*.') ? '*.' : '';
  const name = domainToASCII(x.slice(prefix.length));
  if (!name) throw new Error(`Invalid PSL entry: ${x}`);
  return prefix + name;
});
if (rules.length < 9000 || new Set(rules).size !== rules.length) throw new Error('Incomplete or duplicate PSL rules');
const metadata = {
  source: 'https://publicsuffix.org/list/public_suffix_list.dat',
  version: raw.match(/^\/\/ VERSION: (.+)$/m)?.[1],
  commit: raw.match(/^\/\/ COMMIT: (.+)$/m)?.[1],
  sha256: createHash('sha256').update(raw).digest('hex'),
  license: 'MPL-2.0',
  includesPrivate: true,
};
if (!metadata.version || !metadata.commit) throw new Error('Missing PSL provenance');
const output = `/* Public Suffix List, MPL-2.0. Generated by scripts/update-psl.mjs.\n * Source and full notices: browser/vendor/public_suffix_list.dat and PSL-NOTICE.md.\n * Do not edit the generated data. */\n(function(root) {\n  "use strict";\n  const data = Object.freeze({metadata: Object.freeze(${JSON.stringify(metadata)}), rules: ${JSON.stringify(rules.join('\n'))}});\n  if (typeof module !== "undefined" && module.exports) module.exports = data;\n  else root.EGPSL = data;\n})(globalThis);\n`;
writeFileSync(new URL('../browser/core/psl-data.js', import.meta.url), output);
process.stdout.write(`PSL ${metadata.version}: ${rules.length} rules, SHA-256 ${metadata.sha256}\n`);
